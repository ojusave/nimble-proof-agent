"""Bundle the two UI modules with Python; no frontend toolchain or runtime imports."""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parent.parent

def bundle():
    activity = (ROOT/'web/activity.mjs').read_text().replace('export function ', 'function ').replace('export class ', 'class ')
    search = (ROOT/'web/search.js').read_text()
    return '// Generated by scripts/build_web.py. Edit activity.mjs or search.js.\n' + activity + '\n' + search

if __name__ == '__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    target=ROOT/'web/app.js'
    expected=bundle()
    if args.check:
        if not target.exists() or target.read_text()!=expected:
            raise SystemExit('UI bundle is stale. Run python scripts/build_web.py.')
        print('UI bundle is current.')
    else:
        target.write_text(expected)
        print('Built web/app.js.')
